#!/usr/bin/env bash
# Build the single-file gauth executable from src/.
set -u

ROOT="$(cd "$(dirname "$0")" && pwd -P)"
DIST="$ROOT/dist"
OUT="$DIST/gauth"
VERSION="0.1.0"

MODULES=(
  common
  ui
  config
  clipboard
  ssh
  sshconfig
  git
  account
  settings
  doctor
  commands
  main
)

if [ "${BASH_VERSINFO[0]}" -lt 3 ] || { [ "${BASH_VERSINFO[0]}" -eq 3 ] && [ "${BASH_VERSINFO[1]}" -lt 2 ]; }; then
  printf 'build.sh requires Bash 3.2 or newer\n' >&2
  exit 1
fi

mkdir -p "$DIST" || exit 1
TMP="$(mktemp "$DIST/.gauth.XXXXXX")" || exit 1
trap 'rm -f "$TMP"' EXIT INT TERM

{
  printf '#!/usr/bin/env bash\n'
  printf '# gauth %s - generated by build.sh; edit files in src/ instead.\n' "$VERSION"
  printf '# shellcheck disable=SC2034,SC2154,SC1090\n'
  for module in "${MODULES[@]}"; do
    file="$ROOT/src/${module}.sh"
    if [ ! -f "$file" ]; then
      printf 'build.sh: missing %s\n' "$file" >&2
      exit 1
    fi
    printf '\n# ---------------------------------------------------------------------------\n'
    printf '# %s.sh\n' "$module"
    printf '# ---------------------------------------------------------------------------\n'
    cat "$file" || exit 1
  done
} >"$TMP" || exit 1

chmod 755 "$TMP" || exit 1
bash -n "$TMP" || {
  printf 'build.sh: generated script has a syntax error\n' >&2
  exit 1
}
mv "$TMP" "$OUT" || exit 1
trap - EXIT INT TERM

printf 'Built %s\n' "$OUT"
